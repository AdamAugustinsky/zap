#!/usr/bin/env python3
"""Audits the licences of everything linked into the Go UI build's core.

Lists every crate the headless core depends on (normal and build
dependencies, for both macOS architectures) with its version, source and SPDX
licence expression, and fails on a crate with no licence, with one outside
the allow-list, or from git with no licence file to be found. It writes the
list as a generated section of THIRD-PARTY-NOTICES.md, after upstream's.

    scripts/gnui/licences.py                   # audit and print the section
    scripts/gnui/licences.py --write           # also replace the section in THIRD-PARTY-NOTICES.md
    scripts/gnui/licences.py --check           # fail when the section is not current
    scripts/gnui/licences.py -p zapfast_core   # audit the cdylib with its own features
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from common import MAC_TARGETS, ROOT, output, selection

NOTICES = ROOT / "THIRD-PARTY-NOTICES.md"
BEGIN = "<!-- BEGIN zapfast_core licences: generated by scripts/gnui/licences.py, do not edit -->"
END = "<!-- END zapfast_core licences -->"

# docs/GNUI-MIGRATION-PLAN.md, "Licences of the bundled core". MPL-2.0 is for
# files used unmodified, as crates from the registry are.
ALLOWED = {
    "MIT",
    "Apache-2.0",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "ISC",
    "Zlib",
    "Unicode-3.0",
    "MPL-2.0",
    "CC0-1.0",
    "BSL-1.0",
    "OpenSSL",
    # Approved 2026-10-19: borrow-or-share (MIT-0) and webpki-roots'
    # certificate data (CDLA-Permissive-2.0).
    "MIT-0",
    "CDLA-Permissive-2.0",
}
ALLOWED_EXCEPTIONS = {"LLVM-exception"}

# Native code compiled inside crates, checked by hand against the vendored
# sources (Z0, 2026-10-19). Recheck when one of these crates changes version.
NATIVE = [
    ("libsqlite3-sys", "SQLCipher (`sqlcipher/LICENSE`, BSD-3-Clause style, Zetetic LLC) over SQLite (public domain)"),
    ("openssl-src", "OpenSSL 3 (`openssl/LICENSE.txt`, Apache-2.0)"),
    ("openh264-sys2", "OpenH264 (`upstream/LICENSE`, BSD-2-Clause, Cisco). Built from source, so Cisco's patent licence does not cover it"),
    ("opusic-sys", "libopus (`opus/COPYING`, BSD-3-Clause, Xiph.Org and others)"),
    ("libwebp-sys2", "libwebp (`c_src/COPYING`, BSD-3-Clause, with Google's patent grant in `c_src/PATENTS`)"),
    ("ring", "BoringSSL and OpenSSL-derived code (`LICENSE`, `LICENSE-BoringSSL`, `LICENSE-other-bits`: ISC, OpenSSL, SSLeay)"),
]

LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|UNLICENSE)", re.IGNORECASE)


def tokens(expression: str) -> list[str]:
    # Old crates separate alternatives with "/".
    expression = expression.replace("/", " OR ")
    return re.findall(r"\(|\)|[^\s()]+", expression)


def allowed(expression: str) -> bool:
    """Evaluates an SPDX expression: OR needs one side allowed, AND both."""
    items = tokens(expression)
    at = 0

    def disjunction() -> bool:
        nonlocal at
        result = conjunction()
        while at < len(items) and items[at].upper() == "OR":
            at += 1
            right = conjunction()
            result = result or right
        return result

    def conjunction() -> bool:
        nonlocal at
        result = term()
        while at < len(items) and items[at].upper() == "AND":
            at += 1
            right = term()
            result = result and right
        return result

    def term() -> bool:
        nonlocal at
        if at >= len(items):
            raise ValueError(f"incomplete licence expression {expression!r}")
        if items[at] == "(":
            at += 1
            result = disjunction()
            if at >= len(items) or items[at] != ")":
                raise ValueError(f"unbalanced licence expression {expression!r}")
            at += 1
        else:
            result = items[at].rstrip("+") in ALLOWED
            at += 1
        if at < len(items) and items[at].upper() == "WITH":
            exception = items[at + 1] if at + 1 < len(items) else ""
            at += 2
            result = result and exception in ALLOWED_EXCEPTIONS
        return result

    result = disjunction()
    if at != len(items):
        raise ValueError(f"unparsed licence expression {expression!r}")
    return result


def dependencies(arguments: list[str], targets: list[str]) -> set[tuple[str, str]]:
    """(name, version) of every crate in the core's tree, for any target."""
    found = set()
    for target in targets:
        tree = output(
            ["cargo", "tree", "--locked", "-e", "normal,build", "--prefix", "none"]
            + ["--target", target, "--format", "{p}"]
            + arguments
        )
        for line in tree.splitlines():
            parts = line.split()
            if len(parts) >= 2 and parts[1].startswith("v"):
                found.add((parts[0], parts[1][1:]))
    return found


def source_of(package: dict) -> str:
    source = package.get("source") or "path"
    if source.startswith("registry+"):
        return "crates.io"
    if source.startswith("git+"):
        return source[len("git+") :].split("#")[0]
    return "local"


def licence_file(package: dict) -> Path | None:
    """The crate's licence file, or one in an enclosing directory of its git checkout."""
    directory = Path(package["manifest_path"]).parent
    if package.get("license_file"):
        named = directory / package["license_file"]
        if named.exists():
            return named
    while True:
        for entry in sorted(directory.iterdir()):
            if entry.is_file() and LICENCE_FILE.match(entry.name):
                return entry
        if (directory / ".git").exists() or directory.parent == directory:
            return None
        # A git checkout's directory is named after the short revision.
        if directory.parent.parent.name == "checkouts":
            return None
        directory = directory.parent


def audit(package_name: str | None, targets: list[str]) -> tuple[list[dict], list[str]]:
    metadata = json.loads(
        output(["cargo", "metadata", "--format-version", "1", "--locked", "--all-features"])
    )
    by_key: dict[tuple[str, str], list[dict]] = {}
    for package in metadata["packages"]:
        by_key.setdefault((package["name"], package["version"]), []).append(package)
    workspace = set(metadata["workspace_members"])
    rows, problems = [], []
    for name, version in sorted(dependencies(selection(package_name), targets)):
        for package in by_key.get((name, version), []):
            if package["id"] in workspace:
                continue
            expression = package.get("license")
            source = source_of(package)
            row = {"name": name, "version": version, "source": source, "licence": expression}
            if not expression:
                if package.get("license_file"):
                    row["licence"] = f"see {package['license_file']}"
                problems.append(f"{name} {version}: no SPDX licence expression")
            else:
                try:
                    if not allowed(expression):
                        problems.append(f"{name} {version}: {expression} is outside the allow-list")
                except ValueError as error:
                    problems.append(f"{name} {version}: {error}")
            if source != "crates.io" and source != "local" and licence_file(package) is None:
                problems.append(f"{name} {version}: a git dependency with no licence file")
            row["review"] = any(problem.startswith(f"{name} {version}:") for problem in problems)
            rows.append(row)
    return rows, problems


def section(rows: list[dict], targets: list[str], package_name: str | None) -> str:
    crate = package_name or "zapfast (`--no-default-features --features headless`)"
    lines = [
        BEGIN,
        "",
        "## zapfast_core (Go UI build)",
        "",
        "The Go UI build bundles the core as `libzapfast_core.dylib`. These are the crates",
        f"linked into it: the normal and build dependencies of {crate} for",
        f"{' and '.join(targets)}, with each crate's SPDX licence expression as its",
        "manifest declares it. Every crate's own licence text ships with its source. The",
        "Pidgin sounds above are not in this build, which uses the system's sounds.",
        "",
        "Native code compiled inside crates, checked by hand against the vendored sources:",
        "",
    ]
    lines += [f"- `{name}`: {note}." for name, note in NATIVE]
    lines += [
        "",
        "**Patent risk, open before public distribution:** OpenH264 is compiled from",
        "source into the core for calls. Cisco's patent licence for H.264 covers only the",
        "binaries Cisco itself distributes, so this build carries no H.264 patent licence.",
        "It is unchanged from upstream ZapFast. Before the Go UI build is distributed",
        "publicly, either load Cisco's prebuilt binary at run time or decode and encode",
        "with VideoToolbox.",
        "",
        "Rows marked *review* are outside the allow-list in",
        "`scripts/gnui/licences.py` and wait for a decision.",
        "",
        "| Crate | Version | Source | Licence |",
        "|---|---|---|---|",
    ]
    for row in rows:
        mark = " *review*" if row["review"] else ""
        licence = row["licence"] or "none"
        lines.append(
            f"| {row['name']} | {row['version']} | {row['source']} | {licence}{mark} |"
        )
    lines += ["", END]
    return "\n".join(lines) + "\n"


def replaced(notices: str, generated: str) -> str:
    if BEGIN in notices and END in notices:
        start = notices.index(BEGIN)
        end = notices.index(END) + len(END)
        return notices[:start] + generated.rstrip("\n") + notices[end:]
    return notices.rstrip("\n") + "\n\n" + generated


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("-p", "--package", help="audit this package with its own features")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="update THIRD-PARTY-NOTICES.md")
    mode.add_argument("--check", action="store_true", help="fail when the section is stale")
    options = parser.parse_args()

    rows, problems = audit(options.package, MAC_TARGETS)
    generated = section(rows, MAC_TARGETS, options.package)
    notices = NOTICES.read_text()
    current = replaced(notices, generated)
    stale = current != notices
    if options.write:
        NOTICES.write_text(current)
    elif not options.check:
        print(generated)

    licences = sorted({row["licence"] or "none" for row in rows})
    print(f"{len(rows)} crates, {len(licences)} distinct licence expressions", file=sys.stderr)
    for problem in problems:
        print(f"FAIL {problem}", file=sys.stderr)
    if options.check and stale:
        print("FAIL THIRD-PARTY-NOTICES.md: the zapfast_core section is not current", file=sys.stderr)
        return 1
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
