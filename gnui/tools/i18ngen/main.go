// Command i18ngen compiles i18n/po/*.po into gnui/i18n/tables_gen.go.
//
//	go run ./tools/i18ngen -po i18n/po -out i18n/tables_gen.go
//	go run ./tools/i18ngen -po i18n/po -out i18n/tables_gen.go -check
//
// It does what upstream's fastframe-i18n build step does (it was msgfmt's
// rule): fuzzy messages, empty translations and plurals with an empty form
// are left out, so an untranslated message shows its English source. Each
// language becomes a sorted table of (context, msgid) entries, deflated into
// a string constant (pack), and a plural function in Go. A Plural-Forms expression the generator has no Go code for
// is an error, not a guess.
//
// -check regenerates in memory and exits 1 if the file on disk differs.
package main

import (
	"bytes"
	"compress/flate"
	"encoding/binary"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() { os.Exit(run(os.Args[1:], os.Stdout, os.Stderr)) }

func run(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("i18ngen", flag.ContinueOnError)
	fs.SetOutput(stderr)
	poDir := fs.String("po", "i18n/po", "directory of *.po files")
	out := fs.String("out", "i18n/tables_gen.go", "generated Go file")
	pkg := fs.String("pkg", "i18n", "package name")
	check := fs.Bool("check", false, "fail if -out is not what the .po files generate")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	src, err := Generate(*poDir, *pkg)
	if err != nil {
		fmt.Fprintln(stderr, "i18ngen:", err)
		return 1
	}
	if *check {
		have, err := os.ReadFile(*out)
		if err != nil {
			fmt.Fprintln(stderr, "i18ngen:", err)
			return 1
		}
		if !bytes.Equal(have, src) {
			fmt.Fprintf(stderr, "i18ngen: %s is stale; run go generate ./i18n\n", *out)
			return 1
		}
		fmt.Fprintf(stdout, "%s is up to date\n", *out)
		return 0
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(stderr, "i18ngen:", err)
		return 1
	}
	return 0
}

// message is one compiled entry.
type message struct {
	ctx, id string
	forms   []string
}

// catalog is one parsed .po file.
type catalog struct {
	tag      string // the file stem: pt-BR
	nplurals int
	plural   string // the Plural-Forms expression, normalized
	msgs     []message
}

// Generate compiles every *.po in dir (not the .pot) into Go source.
func Generate(dir, pkg string) ([]byte, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.po"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	if len(files) == 0 {
		return nil, fmt.Errorf("no .po files in %s", dir)
	}
	var cats []*catalog
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		c, err := parsePO(string(data))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", filepath.Base(f), err)
		}
		c.tag = strings.TrimSuffix(filepath.Base(f), ".po")
		cats = append(cats, c)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/i18ngen from i18n/po/*.po; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	for _, c := range cats {
		name := ident(c.tag)
		body, err := pluralGo(c.plural, c.nplurals)
		if err != nil {
			return nil, fmt.Errorf("%s.po: %w", c.tag, err)
		}
		fmt.Fprintf(&b, "func plural%s(n uint64) int {\n%s}\n\n", name, body)
		packed, err := pack(c.msgs)
		if err != nil {
			return nil, fmt.Errorf("%s.po: %w", c.tag, err)
		}
		fmt.Fprintf(&b, "// packed%s is the %s table, %d entries, deflated (catalog.unpack).\n", name, c.tag, len(c.msgs))
		fmt.Fprintf(&b, "const packed%s = ", name)
		for i := 0; i < len(packed); i += 48 {
			if i > 0 {
				b.WriteString(" +\n\t")
			}
			b.WriteString(strconv.Quote(string(packed[i:min(i+48, len(packed))])))
		}
		b.WriteString("\n\n")
	}
	b.WriteString("// catalogs maps a .po file's tag to its compiled catalog.\n")
	b.WriteString("var catalogs = map[string]*catalog{\n")
	for _, c := range cats {
		fmt.Fprintf(&b, "\t%s: {packed: packed%s, plural: plural%s},\n", strconv.Quote(c.tag), ident(c.tag), ident(c.tag))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// pack lays the table out as the i18n package unpacks it, then deflates it:
// the entry count, then each entry's context, msgid and forms (a count, then
// each), every string and count a uvarint length or value. Only the language
// in use is unpacked, so the binary carries about a fifth of the text a
// table of string constants would. compress/flate at BestCompression is
// deterministic; a Go release that changes its output makes -check ask for
// go generate.
func pack(msgs []message) ([]byte, error) {
	var raw []byte
	str := func(s string) {
		raw = binary.AppendUvarint(raw, uint64(len(s)))
		raw = append(raw, s...)
	}
	raw = binary.AppendUvarint(raw, uint64(len(msgs)))
	for _, m := range msgs {
		str(m.ctx)
		str(m.id)
		raw = binary.AppendUvarint(raw, uint64(len(m.forms)))
		for _, f := range m.forms {
			str(f)
		}
	}
	var out bytes.Buffer
	w, err := flate.NewWriter(&out, flate.BestCompression)
	if err != nil {
		return nil, err
	}
	if _, err := w.Write(raw); err != nil {
		return nil, err
	}
	if err := w.Close(); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}

func ident(tag string) string {
	var b strings.Builder
	up := true
	for _, r := range tag {
		if r == '-' || r == '_' {
			up = true
			continue
		}
		if up && r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		up = false
		b.WriteRune(r)
	}
	return b.String()
}

// pluralRules holds the Go code for each Plural-Forms expression in use,
// keyed by the expression without spaces or the outer parentheses.
var pluralRules = map[string]struct {
	n    int
	body string
}{
	"0":        {1, "\treturn 0\n"},
	"n!=1":     {2, "\tif n != 1 {\n\t\treturn 1\n\t}\n\treturn 0\n"},
	"n>1":      {2, "\tif n > 1 {\n\t\treturn 1\n\t}\n\treturn 0\n"},
	"n==1?0:1": {2, "\tif n == 1 {\n\t\treturn 0\n\t}\n\treturn 1\n"},
	"n%10==1&&n%100!=11?0:n%10>=2&&n%10<=4&&(n%100<10||n%100>=20)?1:2": {3,
		"\tif n%10 == 1 && n%100 != 11 {\n\t\treturn 0\n\t}\n" +
			"\tif n%10 >= 2 && n%10 <= 4 && (n%100 < 10 || n%100 >= 20) {\n\t\treturn 1\n\t}\n\treturn 2\n"},
}

func pluralGo(expr string, nplurals int) (string, error) {
	rule, ok := pluralRules[expr]
	if !ok {
		return "", fmt.Errorf("no Go code for the plural rule %q; add it to pluralRules", expr)
	}
	if rule.n != nplurals {
		return "", fmt.Errorf("plural rule %q makes %d forms, the header says nplurals=%d", expr, rule.n, nplurals)
	}
	if nplurals == 1 {
		return "\t_ = n\n" + rule.body, nil
	}
	return rule.body, nil
}

// parsePO reads one catalog, applying upstream's rule for what to leave out.
func parsePO(src string) (*catalog, error) {
	c := &catalog{}
	var cur *raw
	flush := func() error {
		if cur == nil {
			return nil
		}
		r := cur
		cur = nil
		if r.hasID && r.id == "" && r.ctx == "" && !r.hasPlural {
			return c.header(r.str[0])
		}
		if r.fuzzy || !r.hasID {
			return nil
		}
		forms := 1
		if r.hasPlural {
			forms = c.nplurals
			if forms == 0 {
				return fmt.Errorf("plural message %q before the Plural-Forms header", r.id)
			}
		}
		out := make([]string, forms)
		for i := 0; i < forms; i++ {
			s, ok := r.str[i]
			if !ok || s == "" {
				return nil // untranslated or incomplete: leave out whole
			}
			out[i] = s
		}
		c.msgs = append(c.msgs, message{r.ctx, r.id, out})
		return nil
	}

	var add func(string) // where continuation lines go
	for lineNo, line := range strings.Split(src, "\n") {
		line = strings.TrimRight(line, "\r")
		trim := strings.TrimSpace(line)
		fail := func(msg string) error { return fmt.Errorf("line %d: %s", lineNo+1, msg) }
		switch {
		case trim == "":
			if err := flush(); err != nil {
				return nil, err
			}
			add = nil
		case strings.HasPrefix(trim, "#~"):
			// Obsolete entry.
		case strings.HasPrefix(trim, "#,"):
			if cur == nil {
				cur = &raw{str: map[int]string{}}
			}
			if strings.Contains(trim, "fuzzy") {
				cur.fuzzy = true
			}
		case strings.HasPrefix(trim, "#"):
			// A comment between entries.
		case strings.HasPrefix(trim, "\""):
			if add == nil {
				return nil, fail("string outside a message")
			}
			s, err := unquote(trim)
			if err != nil {
				return nil, fail(err.Error())
			}
			add(s)
		default:
			kw, rest, _ := strings.Cut(trim, " ")
			rest = strings.TrimSpace(rest)
			s, err := unquote(rest)
			if err != nil {
				return nil, fail(err.Error())
			}
			if kw == "msgctxt" || kw == "msgid" {
				// A keyword that starts an entry, when the previous one has
				// already seen its msgstr.
				if cur != nil && cur.sawStr {
					if err := flush(); err != nil {
						return nil, err
					}
				}
			}
			if cur == nil {
				cur = &raw{str: map[int]string{}}
			}
			r := cur
			switch {
			case kw == "msgctxt":
				cur.ctx = s
				add = func(s string) { r.ctx += s }
			case kw == "msgid":
				cur.hasID = true
				cur.id = s
				add = func(s string) { r.id += s }
			case kw == "msgid_plural":
				cur.hasPlural = true
				cur.idPlural = s
				add = func(s string) { r.idPlural += s }
			case kw == "msgstr":
				cur.sawStr = true
				cur.str[0] = s
				add = func(s string) { r.str[0] += s }
			case strings.HasPrefix(kw, "msgstr["):
				i, err := strconv.Atoi(strings.TrimSuffix(strings.TrimPrefix(kw, "msgstr["), "]"))
				if err != nil {
					return nil, fail("bad msgstr index")
				}
				cur.sawStr = true
				cur.str[i] = s
				add = func(s string) { r.str[i] += s }
			default:
				return nil, fail("unknown keyword " + kw)
			}
		}
	}
	if err := flush(); err != nil {
		return nil, err
	}
	if c.plural == "" {
		return nil, fmt.Errorf("no Plural-Forms header")
	}
	sort.SliceStable(c.msgs, func(i, j int) bool {
		a, b := c.msgs[i], c.msgs[j]
		if a.ctx != b.ctx {
			return a.ctx < b.ctx
		}
		return a.id < b.id
	})
	for i := 1; i < len(c.msgs); i++ {
		if c.msgs[i].ctx == c.msgs[i-1].ctx && c.msgs[i].id == c.msgs[i-1].id {
			return nil, fmt.Errorf("duplicate message %q (context %q)", c.msgs[i].id, c.msgs[i].ctx)
		}
	}
	return c, nil
}

// raw is an entry while it is being read.
type raw struct {
	ctx, id, idPlural string
	hasID, hasPlural  bool
	fuzzy, sawStr     bool
	str               map[int]string
}

func (c *catalog) header(h string) error {
	for _, line := range strings.Split(h, "\n") {
		k, v, ok := strings.Cut(line, ":")
		if !ok || strings.TrimSpace(k) != "Plural-Forms" {
			continue
		}
		var expr string
		for _, part := range strings.Split(v, ";") {
			part = strings.TrimSpace(part)
			switch {
			case strings.HasPrefix(part, "nplurals="):
				n, err := strconv.Atoi(strings.TrimPrefix(part, "nplurals="))
				if err != nil {
					return fmt.Errorf("bad nplurals in %q", line)
				}
				c.nplurals = n
			case strings.HasPrefix(part, "plural="):
				expr = strings.TrimPrefix(part, "plural=")
			}
		}
		expr = strings.Join(strings.Fields(expr), "")
		for len(expr) > 2 && expr[0] == '(' && expr[len(expr)-1] == ')' && balanced(expr[1:len(expr)-1]) {
			expr = expr[1 : len(expr)-1]
		}
		c.plural = expr
	}
	if c.nplurals == 0 || c.plural == "" {
		return fmt.Errorf("the header has no usable Plural-Forms")
	}
	return nil
}

func balanced(s string) bool {
	d := 0
	for _, r := range s {
		switch r {
		case '(':
			d++
		case ')':
			d--
			if d < 0 {
				return false
			}
		}
	}
	return d == 0
}

func unquote(s string) (string, error) {
	if len(s) < 2 || s[0] != '"' || s[len(s)-1] != '"' {
		return "", fmt.Errorf("expected a quoted string, got %q", s)
	}
	s = s[1 : len(s)-1]
	if !strings.Contains(s, "\\") {
		return s, nil
	}
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		if s[i] != '\\' {
			b.WriteByte(s[i])
			continue
		}
		i++
		if i == len(s) {
			return "", fmt.Errorf("dangling backslash")
		}
		switch s[i] {
		case 'n':
			b.WriteByte('\n')
		case 't':
			b.WriteByte('\t')
		case 'r':
			b.WriteByte('\r')
		case '"', '\\':
			b.WriteByte(s[i])
		default:
			b.WriteByte('\\')
			b.WriteByte(s[i])
		}
	}
	return b.String(), nil
}
